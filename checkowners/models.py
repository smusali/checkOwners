"""Data models for checkOwners. Only dataclasses; no other classes."""

from __future__ import annotations

from dataclasses import dataclass, field
from datetime import datetime
from typing import Literal

Severity = Literal["low", "medium", "high", "critical"]
DriftMode = Literal["commit", "repo", "both"]
QualificationStrategy = Literal["adaptive", "threshold"]

OWNERSHIP_MODEL_VERSION = "ownership-v3"
DEPRECATED_SCORE_KEY = "confidence"


@dataclass(frozen=True)
class AnalysisConfig:
    lookback_days: int = 365
    min_commits: int = 1
    top_n_owners: int = 3
    confidence_threshold: float = 0.3
    exclude_bots: bool = True


@dataclass(frozen=True)
class QualificationConfig:
    strategy: QualificationStrategy = "adaptive"
    min_commits: int = 1
    strong_blame_override: float = 0.5


@dataclass(frozen=True)
class ScoringConfig:
    recency_half_life_days: int = 90
    recency_weight: float = 0.35
    frequency_weight: float = 0.25
    blame_weight: float = 0.25
    review_weight: float = 0.15
    recency_reliability: float = 1.0
    frequency_reliability: float = 1.0
    blame_reliability: float = 1.0
    review_reliability: float = 1.0


@dataclass(frozen=True)
class DecayConfig:
    threshold_days: int = 180
    alert_on_decay: bool = True


@dataclass(frozen=True)
class BusFactorConfig:
    critical_threshold: int = 1
    warn_threshold: int = 2


@dataclass(frozen=True)
class PathsConfig:
    #: CODEOWNERS itself is excluded: sync commits would otherwise make
    #: whoever runs the tool the inferred "owner" of the generated file,
    #: perturbing every subsequent run.
    exclude: tuple[str, ...] = (
        "*.lock",
        "package-lock.json",
        "pnpm-lock.yaml",
        "dist/**",
        "vendor/**",
        "node_modules/**",
        "*.generated.*",
        "*.min.js",
        "*.min.css",
        "*.map",
        "*.whl",
        ".github/CODEOWNERS",
        "CODEOWNERS",
        "docs/CODEOWNERS",
    )


@dataclass(frozen=True)
class OutputConfig:
    header: str = "# Generated by checkOwners. Do not edit manually."
    include_unowned: bool = False
    include_confidence: bool = False
    consolidate: bool = True


@dataclass(frozen=True)
class DriftConfig:
    mode: DriftMode = "commit"
    min_confidence_delta: float = 0.2


@dataclass(frozen=True)
class NotificationsConfig:
    webhook_url: str = ""
    include_unchanged: bool = False
    severity_threshold: Severity = "medium"


@dataclass(frozen=True)
class GithubConfig:
    org: str = ""
    resolve_handles: bool = True
    resolve_teams: bool = True
    api_enabled: bool = False


@dataclass(frozen=True)
class Config:
    analysis: AnalysisConfig = field(default_factory=AnalysisConfig)
    qualification: QualificationConfig = field(default_factory=QualificationConfig)
    scoring: ScoringConfig = field(default_factory=ScoringConfig)
    decay: DecayConfig = field(default_factory=DecayConfig)
    bus_factor: BusFactorConfig = field(default_factory=BusFactorConfig)
    paths: PathsConfig = field(default_factory=PathsConfig)
    output: OutputConfig = field(default_factory=OutputConfig)
    drift: DriftConfig = field(default_factory=DriftConfig)
    notifications: NotificationsConfig = field(default_factory=NotificationsConfig)
    github: GithubConfig = field(default_factory=GithubConfig)


@dataclass(frozen=True)
class SignalScore:
    available: bool
    score: float = 0.0

    def as_payload(self) -> dict[str, bool | float]:
        if not self.available:
            return {"available": False}
        return {"score": round(self.score, 4), "available": True}


@dataclass(frozen=True)
class ConfidenceScore:
    """Per-signal breakdown of a single owner's ownership score for a path."""

    total: float
    recency: SignalScore
    frequency: SignalScore
    blame: SignalScore
    review: SignalScore

    def signals_payload(self) -> dict[str, dict[str, bool | float]]:
        return {
            "recency": self.recency.as_payload(),
            "frequency": self.frequency.as_payload(),
            "blame": self.blame.as_payload(),
            "review": self.review.as_payload(),
        }


@dataclass(frozen=True)
class OwnerEntry:
    """A single owner of a path with score, evidence quality, and provenance."""

    handle: str
    ownership_score: float
    last_commit: datetime | None
    commits: int
    evidence_quality: float = 1.0
    score_breakdown: ConfidenceScore | None = None

    @property
    def confidence(self) -> float:
        return self.ownership_score

    @property
    def score_label(self) -> str:
        return f"{self.ownership_score:.2f}/{self.evidence_quality:.2f}"


@dataclass(frozen=True)
class DecayWarning:
    handle: str
    path: str
    last_commit: datetime
    days_since_last_commit: int
    historical_confidence: float


@dataclass(frozen=True)
class PathOwnership:
    """All information known about a single path's ownership."""

    owners: tuple[OwnerEntry, ...]
    qualified_owner_count: int
    decay_warnings: tuple[DecayWarning, ...] = ()


@dataclass(frozen=True)
class OwnershipMap:
    """Confidence-scored ownership across all paths."""

    paths: dict[str, PathOwnership]
    last_analyzed: datetime


@dataclass(frozen=True)
class ExpertiseRank:
    """Per-path ranking entry for the expertise command."""

    handle: str
    confidence: float
    commits: int
    last_commit: datetime | None


@dataclass(frozen=True)
class TeamCluster:
    """Inferred team boundary from commit co-occurrence."""

    name: str
    members: tuple[str, ...]
    primary_paths: tuple[str, ...]
    declared: bool = False


@dataclass(frozen=True)
class BusFactor:
    path: str
    qualified_owner_count: int
    contributors_above_threshold: tuple[str, ...]
    recommended_backups: tuple[str, ...]


@dataclass(frozen=True)
class DriftEntry:
    path: str
    confidence_delta: float
    reason: str = ""
    qualified_owner_count: int | None = None
    decay: bool = False


@dataclass(frozen=True)
class DriftResult:
    stale: tuple[DriftEntry, ...]
    missing: tuple[DriftEntry, ...]
    changed: tuple[DriftEntry, ...]
    drift_detected: bool
    #: Human-readable caveats about the comparison (e.g. inferred owners are
    #: raw emails while CODEOWNERS uses @handles, making owner-set comparison
    #: impossible without handle resolution).
    notes: tuple[str, ...] = ()

    @property
    def max_confidence_delta(self) -> float:
        entries = (*self.stale, *self.missing, *self.changed)
        if not entries:
            return 0.0
        return max(abs(e.confidence_delta) for e in entries)
