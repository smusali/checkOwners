@dataclass(frozen=True)
class _Key:
    """One YAML key: the dataclass field it sets and the reader that checks it.

    `name` is the key as it appears in the file, `read` takes the raw value and
    the dotted key path and returns the field value, and `field` is the target
    field when it differs from `name`.
    """

    name: str
    read: Callable[[object, str], object]
    field: str = ""


def _scalar(value: object, key: str, expected: str) -> int | float | str | bool:
    """Return `value` when it is a scalar YAML reader can convert, else raise."""
    if isinstance(value, int | float | str | bool):
        return value
    msg = f"{key} must be {expected}"
    raise ValueError(msg)


def _as_int(value: object, key: str) -> int:
    return int(_scalar(value, key, "an integer"))


def _as_float(value: object, key: str) -> float:
    return float(_scalar(value, key, "a number"))


def _as_bool(value: object, _key: str) -> bool:
    return bool(value)


def _as_text(value: object, _key: str) -> str:
    return str(value)


def _literal(allowed: frozenset[str], expected: str) -> Callable[[object, str], str]:
    """Return a reader that accepts only one of `allowed`."""

    def read(value: object, key: str) -> str:
        text = str(value)
        if text not in allowed:
            msg = f"Invalid {key}: {text!r}; expected {expected}"
            raise ValueError(msg)
        return text

    return read


def _at_least(minimum: int) -> Callable[[object, str], int]:
    """Return a reader that accepts an integer no smaller than `minimum`."""

    def read(value: object, key: str) -> int:
        number = _as_int(value, key)
        if number < minimum:
            msg = f"Invalid {key}: {number!r}; expected an integer >= {minimum}"
            raise ValueError(msg)
        return number

    return read


def _between(
    low: float,
    high: float,
    *,
    strict: bool = True,
) -> Callable[[object, str], float]:
    """Return a reader that accepts a number in the closed interval.

    `strict` rejects a value that is not already a number; otherwise anything
    `float` accepts is read.
    """

    def read(value: object, key: str) -> float:
        if strict and (isinstance(value, bool) or not isinstance(value, int | float)):
            msg = f"Invalid {key}: {value!r}; expected a number in [{low:g}, {high:g}]"
            raise ValueError(msg)
        number = _as_float(value, key)
        if number < low or number > high:
            msg = f"Invalid {key}: {number!r}; expected a number in [{low:g}, {high:g}]"
            raise ValueError(msg)
        return number

    return read


def _at_most(maximum: int) -> Callable[[object, str], int]:
    """Return a reader that accepts a positive integer no larger than `maximum`."""

    def read(value: object, key: str) -> int:
        number = _require_positive_int(value, key)
        if number > maximum:
            msg = f"{key} must be from 1 to {maximum}"
            raise ValueError(msg)
        return number

    return read


def _string_list(value: object, _key: str) -> tuple[str, ...]:
    if not isinstance(value, list):
        return ()
    return tuple(str(item) for item in value)


