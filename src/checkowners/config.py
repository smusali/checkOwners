def _allowed(keys: tuple[_Key, ...], *extra: str) -> frozenset[str]:
    """Return the key names a section accepts, plus any write-only `extra`."""
    return frozenset({key.name for key in keys} | set(extra))


def _section(
    cls: Callable[..., _SectionT],
    prefix: str,
    data: Mapping[str, Any],
    keys: tuple[_Key, ...],
) -> _SectionT:
    """Return `cls` built from the keys of `data` that `keys` names."""
    kwargs: dict[str, Any] = {}
    for key in keys:
        if key.name not in data:
            continue
        kwargs[key.field or key.name] = key.read(data[key.name], f"{prefix}.{key.name}")
    return cls(**kwargs)


