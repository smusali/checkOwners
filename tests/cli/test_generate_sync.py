"""Contracts for the commands that write CODEOWNERS or propose a change."""

from __future__ import annotations

import json
from collections.abc import Mapping

import pytest
from tests.conftest import Cli, fake_api, reply

from checkowners.github import ApiResponse

_HEADER = "# Generated by checkOwners. Do not edit manually."
_PULL_URL = "https://github.com/acme/app/pull/12"


def test_print_lists_every_scored_path(cli: Cli) -> None:
    payload = cli.json("print")
    assert "src/app.py" in payload.child("paths")


def test_generate_writes_a_file_with_the_configured_header(cli: Cli) -> None:
    payload = cli.json("generate", "--force")
    content = payload.text("content")
    assert content.startswith(_HEADER)
    assert "src/app.py" in content
    assert payload.whole("rules_written") > 0
    written = (cli.repo.path / ".github" / "CODEOWNERS").read_text(encoding="utf-8")
    assert written == content


def test_generate_refuses_to_overwrite_without_force(cli: Cli) -> None:
    cli.codeowners("* @alice\n")
    result = cli.run("generate")
    assert result.exit_code == 2
    assert "@alice" in (cli.repo.path / ".github" / "CODEOWNERS").read_text(encoding="utf-8")


def test_generate_keeps_a_manual_block_byte_for_byte(cli: Cli) -> None:
    manual = "# checkowners:manual:start\n/infra/ @platform\n# checkowners:manual:end\n"
    cli.codeowners(manual)
    result = cli.run("generate", "--force")
    assert result.exit_code == 0
    written = (cli.repo.path / ".github" / "CODEOWNERS").read_text(encoding="utf-8")
    assert manual in written


@pytest.mark.parametrize("dialect", ["github", "gitlab"])
def test_generate_accepts_the_implemented_dialects(cli: Cli, dialect: str) -> None:
    result = cli.run("generate", "--force", "--dialect", dialect)
    assert result.exit_code == 0


def test_generate_rejects_an_unknown_dialect(cli: Cli) -> None:
    result = cli.run("generate", "--force", "--dialect", "bitbucket")
    assert result.exit_code == 2
    assert "Unknown dialect" in result.stdout


def test_baseline_create_records_the_current_findings(cli: Cli) -> None:
    payload = cli.json("baseline", "create")
    target = cli.repo.path / payload.text("path")
    assert target.is_file()
    stored = json.loads(target.read_text(encoding="utf-8"))
    assert set(stored) == {"findings"}


def test_a_baseline_is_reused_by_drift(cli: Cli) -> None:
    created = cli.json("baseline", "create")
    baseline = created.text("path")
    first = cli.run("drift")
    second = cli.run("drift", "--baseline", baseline)
    assert "Baselined: 0" in first.stdout
    assert second.exit_code == 0


def test_sync_dry_run_writes_nothing_and_opens_nothing(cli: Cli) -> None:
    cli.codeowners(f"{_HEADER}\n\n* @old\n")
    with fake_api() as api:
        result = cli.run("sync", "--commit", "--dry-run")
    assert result.exit_code == 0
    assert "@old" in (cli.repo.path / ".github" / "CODEOWNERS").read_text(encoding="utf-8")
    assert api.paths("POST") == []
    assert api.paths("PATCH") == []


def test_sync_opens_one_reconciliation_pull_request(
    cli: Cli,
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    cli.codeowners(f"{_HEADER}\n\n* @old\n")
    monkeypatch.setenv("GITHUB_TOKEN", "ghs_test")
    monkeypatch.setenv("GITHUB_REPOSITORY", "acme/app")
    state = {"branch": False, "pull": False}
    posts: list[str] = []

    def answer(
        method: str,
        path: str,
        payload: Mapping[str, object] | None,
    ) -> ApiResponse | None:
        if method == "POST" and path.endswith("/pulls"):
            posts.append(json.dumps(payload))
            state["pull"] = True
            return reply({"number": 12, "html_url": _PULL_URL})
        if path == "/repos/acme/app":
            return reply({"default_branch": "main"})
        if method == "GET" and "/git/ref/heads/main" in path:
            return reply({"object": {"sha": "base"}})
        if method == "GET" and "/git/commits/base" in path:
            return reply({"sha": "base", "tree": {"sha": "tree0"}})
        if method == "POST" and path.endswith("/git/blobs"):
            return reply({"sha": "blob1"})
        if method == "POST" and path.endswith("/git/trees"):
            return reply({"sha": "tree1"})
        if method == "POST" and path.endswith("/git/commits"):
            return reply({"sha": "commit1"})
        if method == "POST" and path.endswith("/git/refs"):
            return reply({"ref": "refs/heads/checkowners/reconcile-codeowners"})
        if method == "GET" and "/pulls?" in path:
            if not state["pull"]:
                return reply([])
            return reply([{"number": 12, "html_url": _PULL_URL}])
        if method == "PATCH" and "/git/refs/heads/" in path:
            if not state["branch"]:
                state["branch"] = True
                return reply(status=404)
            return reply({"object": {"sha": "commit1"}})
        if method == "PATCH" and "/pulls/12" in path:
            return reply({"number": 12, "html_url": _PULL_URL})
        return None

    with fake_api(handler=answer):
        created = cli.json("sync", "--pr")
        updated = cli.json("sync", "--pull-request")
    pull = created.child("pull_request")
    assert pull.whole("number") == 12
    assert pull.flag("updated") is False
    assert created.flag("committed") is False
    second = updated.child("pull_request")
    assert second.flag("updated") is True
    assert second.text("url") == _PULL_URL
    assert len(posts) == 1
    body = json.loads(posts[0])
    assert body["title"] == "chore: reconcile CODEOWNERS ownership drift"
    assert "Inferred ownership is evidence, not accountability." in body["body"]


def test_sync_reports_nothing_to_open_when_the_file_already_matches(cli: Cli) -> None:
    generated = cli.json("generate", "--force")
    cli.codeowners(generated.text("content"))
    with fake_api():
        result = cli.run("sync", "--dry-run")
    assert result.exit_code == 0
    assert "nothing to open" in result.stdout
