def _write_config(tmp_path: Path, content: str) -> Path:
    config_dir = tmp_path / ".github"
    config_dir.mkdir(exist_ok=True)
    (config_dir / "checkowners.yml").write_text(content, encoding="utf-8")
    return tmp_path


