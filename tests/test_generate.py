def test_generate_overwrites_own_output(tmp_path: Path) -> None:
    """Regenerating over a previously generated file needs no --force."""
    ownership = _make_ownership({"src/main.py": (_entry("@alice", 0.9),)})
    generate_codeowners(tmp_path, ownership, _zero_threshold())
    target = tmp_path / ".github" / "CODEOWNERS"
    original = target.read_text(encoding="utf-8")
    header = "# Generated by checkOwners. Do not edit manually.\n\n"
    manual = (
        "# checkowners:manual:start\n"
        "/security/** @security-team\n"
        "/legal/**    @security-team\n"
        "# checkowners:manual:end"
    )
    assert original.startswith(header)
    seeded = f"{header}{manual}\n\n{original[len(header) :]}"
    target.write_text(seeded, encoding="utf-8")
    preview = generate_codeowners(tmp_path, ownership, _zero_threshold(), write=False)
    assert target.read_text(encoding="utf-8") == seeded
    assert manual in preview.content
    generate_codeowners(tmp_path, ownership, _zero_threshold())
    written = target.read_text(encoding="utf-8")
    assert manual in written
    assert written.index(manual) < written.index("# checkowners:generated:start")
    assert written.index("# checkowners:generated:start") < written.index("/src/main.py")
    assert written.index("/src/main.py") < written.index("# checkowners:generated:end")
    assert written.startswith(header)
    assert written.count(header) == 1


def test_generate_keeps_manual_region_without_trailing_newline(tmp_path: Path) -> None:
    ownership = _make_ownership({"src/main.py": (_entry("@alice", 0.9),)})
    target = tmp_path / ".github" / "CODEOWNERS"
    target.parent.mkdir(parents=True)
    manual = "# checkowners:manual:start\n/security/** @security-team\n# checkowners:manual:end"
    header = "# Generated by checkOwners. Do not edit manually.\n\n"
    target.write_text(f"{header}{manual}", encoding="utf-8")
    result = generate_codeowners(tmp_path, ownership, _zero_threshold())
    assert manual in result.content
    assert result.content.index(manual) < result.content.index("/src/main.py")
    assert result.content.endswith("\n")
    assert not result.content.endswith("\n\n")


@pytest.mark.parametrize(
    ("original", "message"),
    [
        (
            "# Generated by checkOwners. Do not edit manually.\n\n"
            "# checkowners:manual:start\n/security/** @security-team\n",
            "manual:end",
        ),
        ("# checkowners:generated:start\n", "generated:end"),
        ("# checkowners:generated:end\n", "generated:start"),
        ("# checkowners:manual:end\n", "manual:start"),
        (
            "# checkowners:manual:start\n/a @x\n# checkowners:manual:end\n"
            "# checkowners:manual:start\n",
            "repeats a manual block",
        ),
        (
            "# checkowners:generated:start\n/a @x\n# checkowners:generated:end\n"
            "# checkowners:generated:start\n",
            "repeats a generated block",
        ),
        (
            "# checkowners:manual:start\n# checkowners:generated:start\n",
            "is inside the manual block",
        ),
        (
            "# checkowners:generated:start\n# checkowners:manual:end\n",
            "is inside the generated block",
        ),
        (
            "# checkowners:manual:start\n# checkowners:manual:start\n",
            "repeats an open manual block",
        ),
        (
            "# checkowners:generated:start\n# checkowners:generated:start\n",
            "repeats an open generated block",
        ),
    ],
)
def test_generate_refuses_unclosed_manual_region(
    tmp_path: Path, original: str, message: str
) -> None:
    ownership = _make_ownership({"src/main.py": (_entry("@alice", 0.9),)})
    target = tmp_path / ".github" / "CODEOWNERS"
    target.parent.mkdir(parents=True)
    target.write_text(original, encoding="utf-8")
    with pytest.raises(CodeownersGenerateError, match=message):
        generate_codeowners(tmp_path, ownership, _zero_threshold())
    assert target.read_text(encoding="utf-8") == original


