def test_generate_refuses_to_overwrite_handwritten_file(tmp_path: Path) -> None:
    """A curated CODEOWNERS (no machine header) must never be clobbered."""
    target = tmp_path / ".github" / "CODEOWNERS"
    target.parent.mkdir(parents=True)
    target.write_text("# Hand-curated\nsrc/ @human\n", encoding="utf-8")
    ownership = _make_ownership({"src/main.py": (_entry("@alice", 0.9),)})
    with pytest.raises(CodeownersOverwriteError) as exc_info:
        generate_codeowners(tmp_path, ownership, _zero_threshold())
    assert str(exc_info.value) == (
        f"{target} exists but was not generated by checkOwners "
        "(machine-generated header not found). Re-run with --force to overwrite it."
    )
    assert "@human" in target.read_text(encoding="utf-8")


def test_generate_force_overwrites_handwritten_file(tmp_path: Path) -> None:
    target = tmp_path / ".github" / "CODEOWNERS"
