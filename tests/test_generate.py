def test_confidence_threshold_filters_owners() -> None:
    config = Config(analysis=AnalysisConfig(confidence_threshold=0.5))
    ownership = _make_ownership(
        {"src/main.py": (_entry("@alice", 0.9), _entry("@bob", 0.2))},
    )
    content = _build_codeowners_content(ownership, config)
    assert "@bob" not in content
    assert "/src/main.py @alice" in content
    exact = _make_ownership({"/src/main.py": (_entry("@ada", 0.5),)})
    kept = _build_codeowners_content(exact, config)
    assert "/src/main.py @ada" in kept


def test_include_confidence_annotations() -> None:
    config = _zero_threshold(include_confidence=True)
    ownership = _make_ownership({"src/main.py": (_entry("@alice", 0.92),)})
    content = _build_codeowners_content(ownership, config)
    assert "# @alice(0.92/1.00)" in content
    pair = _make_ownership({"src/main.py": (_entry("@alice", 0.92), _entry("@bob", 0.40))})
    paired = _build_codeowners_content(pair, config)
    lines = paired.splitlines()
    heading = "# Confidence scores reflect each owner's expertise as of"
    assert heading in lines
    assert lines[lines.index(heading) - 1] == ""
    assert "# @alice(0.92/1.00) @bob(0.40/1.00)" in paired


